-- =============================================================================
-- PostgreSQL: núcleo transacional do marketplace (R1)
--
-- R1: registrar um pedido com seus itens e baixar o estoque de forma que
-- "ou tudo acontece ou nada acontece". Por isso estes dados ficam num banco
-- relacional ACID: uma única transação insere pedido, itens e pagamento e
-- baixa o estoque; se algo falhar, o ROLLBACK desfaz tudo.
--
-- O script é idempotente: apaga e recria as tabelas, para a carga poder ser
-- refeita do zero quantas vezes for preciso.
-- =============================================================================

DROP TABLE IF EXISTS pagamento, item_pedido, pedido, produto_estoque, cliente CASCADE;

-- -----------------------------------------------------------------------------
-- cliente: quem compra. E-mail e CPF são únicos (regra de negócio garantida
-- pelo banco, não só pela aplicação).
-- -----------------------------------------------------------------------------
CREATE TABLE cliente (
    id          INTEGER      PRIMARY KEY,          -- mesmo id usado em todos os bancos
    nome        VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL UNIQUE,
    cpf         CHAR(14)     NOT NULL UNIQUE,      -- formato 000.000.000-00
    cidade      VARCHAR(80)  NOT NULL,
    uf          CHAR(2)      NOT NULL,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- produto_estoque: só o que a transação de compra precisa (preço e saldo).
-- O catálogo completo, com os atributos de cada categoria, fica no MongoDB (R2).
-- Aqui ficam nome e categoria apenas para as consultas de pedido ficarem legíveis.
--
-- CHECK (estoque >= 0) é a "segunda barreira": mesmo que a aplicação erre a
-- conta, o banco recusa deixar o estoque negativo.
-- -----------------------------------------------------------------------------
CREATE TABLE produto_estoque (
    produto_id     INTEGER       PRIMARY KEY,      -- mesmo id do MongoDB/Redis/Neo4j
    nome           VARCHAR(160)  NOT NULL,
    categoria      VARCHAR(20)   NOT NULL,
    preco          NUMERIC(10,2) NOT NULL CHECK (preco >= 0),
    estoque        INTEGER       NOT NULL CHECK (estoque >= 0),
    atualizado_em  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- pedido: cabeçalho da compra. O id é IDENTITY "BY DEFAULT" para aceitar os
-- ids do dataset na carga e gerar os próximos sozinho nas compras novas.
-- -----------------------------------------------------------------------------
CREATE TABLE pedido (
    id           INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   INTEGER       NOT NULL REFERENCES cliente (id),
    criado_em    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    status       VARCHAR(12)   NOT NULL
                 CHECK (status IN ('pago', 'enviado', 'entregue', 'cancelado')),
    valor_total  NUMERIC(12,2) NOT NULL CHECK (valor_total >= 0)
);

-- -----------------------------------------------------------------------------
-- item_pedido: um produto dentro de um pedido.
-- PK composta (pedido_id, produto_id): o mesmo produto não aparece duas vezes
-- no pedido (aumenta-se a quantidade). preco_unitario é copiado do produto no
-- momento da compra, para o histórico não mudar se o preço mudar depois.
-- ON DELETE CASCADE: item não existe sem o pedido.
-- -----------------------------------------------------------------------------
CREATE TABLE item_pedido (
    pedido_id       INTEGER       NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    produto_id      INTEGER       NOT NULL REFERENCES produto_estoque (produto_id),
    quantidade      INTEGER       NOT NULL CHECK (quantidade > 0),
    preco_unitario  NUMERIC(10,2) NOT NULL CHECK (preco_unitario >= 0),
    PRIMARY KEY (pedido_id, produto_id)
);

-- -----------------------------------------------------------------------------
-- pagamento: um por pedido (UNIQUE em pedido_id = relacionamento 1:1).
-- -----------------------------------------------------------------------------
CREATE TABLE pagamento (
    id         INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id  INTEGER       NOT NULL UNIQUE REFERENCES pedido (id) ON DELETE CASCADE,
    metodo     VARCHAR(15)   NOT NULL
               CHECK (metodo IN ('pix', 'cartao_credito', 'cartao_debito', 'boleto')),
    valor      NUMERIC(12,2) NOT NULL CHECK (valor >= 0),
    parcelas   SMALLINT      NOT NULL DEFAULT 1 CHECK (parcelas BETWEEN 1 AND 12),
    status     VARCHAR(10)   NOT NULL CHECK (status IN ('aprovado', 'recusado')),
    pago_em    TIMESTAMPTZ                          -- NULL quando recusado
);

-- -----------------------------------------------------------------------------
-- Índices para as consultas mais comuns. (As PKs e UNIQUEs já criam índice.)
-- -----------------------------------------------------------------------------
-- "pedidos de um cliente, do mais recente ao mais antigo"
CREATE INDEX idx_pedido_cliente_data ON pedido (cliente_id, criado_em DESC);
-- "em quais pedidos este produto aparece" (a PK de item_pedido começa por pedido_id
-- e não ajuda nessa busca)
CREATE INDEX idx_item_pedido_produto ON item_pedido (produto_id);
